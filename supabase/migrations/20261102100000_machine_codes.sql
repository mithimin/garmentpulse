-- =============================================================================
-- Migration 12: a short code for every machine
-- =============================================================================
-- What this file does, in plain words:
--   1. Adds ONE new optional column to the machines table: `code`, a short
--      label such as SM-01 (Sewing machine 01) or CM-03 (Cutting machine 03).
--      Two machines can never share a code. It starts EMPTY for new machines.
--   2. Fills in the codes of the 5 machines that already exist (the test data),
--      so the cloud project does not need a second step.
--   3. Changes the functions that send machines to the apps, so that the code
--      travels next to the name:
--        * report_json   -> inside every report: machine.code
--        * list_machines -> code
--      Every other function that returns a report (list_my_reports,
--      list_reports, get_report, create_report, assign_technician, accept_job,
--      update_job_status, list_my_jobs) already uses report_json, so they get
--      the new field for free.
--
-- Why: the website's Machine map draws each machine with its code written under
-- it. Mithi asked for it in requests/sakib/2026-11-02-machine-code.md.
--
-- How the apps use it (docs/api-contract.md section 3):
--   * The code is OPTIONAL. When a machine has none, the field is `null`.
--   * Nothing is generated by the apps. A person (Sakib) types each code.
--
-- Nothing else changes: the same function names, inputs, permissions and error
-- codes. Only an extra field appears in the results, so the apps keep working
-- before and after this file. "create or replace" keeps the existing permissions
-- of each function.
--
-- Rules for this folder (see supabase/CLAUDE.md):
--   * Never edit an old migration. Add a NEW file for every change.
-- =============================================================================


-- -----------------------------------------------------------------------------
-- 1. The new, optional, unique column
-- -----------------------------------------------------------------------------
-- A code is either empty or 1 to 20 letters, numbers and dashes, written in
-- capital letters. `unique` allows many empty codes but never two equal ones.
-- The table stays locked: this column inherits the lock.
alter table public.machines
  add column code text unique
  check (code is null or code ~ '^[A-Z0-9][A-Z0-9-]{0,19}$');


-- -----------------------------------------------------------------------------
-- 2. The codes of the machines that exist today
-- -----------------------------------------------------------------------------
update public.machines m
set code = v.code
from (values
  ('Sewing machine 01',   'SM-01'),
  ('Sewing machine 02',   'SM-02'),
  ('Sewing machine 14',   'SM-14'),
  ('Cutting machine 03',  'CM-03'),
  ('Pressing machine 01', 'PM-01')
) as v (name, code)
where m.name = v.name
  and m.code is null;


-- -----------------------------------------------------------------------------
-- 3. One report, in the shape of docs/api-contract.md section 3
-- -----------------------------------------------------------------------------
-- Same as migration 10, plus machine.code. `technician` is still JSON null when
-- nobody is assigned yet.
create or replace function public.report_json(p_report public.reports)
returns jsonb
language sql
stable
security definer
set search_path = ''
as $$
  select jsonb_build_object(
    'id', p_report.id,
    'machine', (
      select jsonb_build_object(
        'id', m.id, 'name', m.name, 'name_bn', m.name_bn, 'code', m.code
      )
      from public.machines m
      where m.id = p_report.machine_id
    ),
    'description', p_report.description,
    'status', p_report.status,
    'reported_by', (
      select jsonb_build_object(
        'id', w.id, 'display_name', w.display_name, 'display_name_bn', w.display_name_bn
      )
      from public.profiles w
      where w.id = p_report.reported_by
    ),
    'technician', (
      select jsonb_build_object(
        'id', t.id, 'display_name', t.display_name, 'display_name_bn', t.display_name_bn
      )
      from public.profiles t
      where t.id = p_report.technician_id
    ),
    'accepted_at', p_report.accepted_at,
    'created_at', p_report.created_at,
    'updated_at', p_report.updated_at
  );
$$;


-- -----------------------------------------------------------------------------
-- 4. The machine list (worker's dropdown, manager)
-- -----------------------------------------------------------------------------
create or replace function public.list_machines()
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
begin
  perform public.require_role(array['worker', 'manager']::public.user_role[]);

  return (
    select coalesce(
      jsonb_agg(
        jsonb_build_object(
          'id', m.id, 'name', m.name, 'name_bn', m.name_bn, 'code', m.code
        )
        order by m.name
      ),
      '[]'::jsonb
    )
    from public.machines m
  );
end;
$$;
