-- =============================================================================
-- Migration 13: a fixed seat (place on the Machine map) for every machine
-- =============================================================================
-- What this file does, in plain words:
--   1. Adds ONE new optional column to the machines table: `seat`, the place of
--      the machine on the website's Machine map. A seat is a row letter and a
--      place number, for example A3 (row A, place 3). Two machines can never
--      share a seat. It starts EMPTY for new machines.
--   2. Fills in the seats of the 5 machines that already exist, in the same
--      order the map shows them today (sorted by name), so nothing moves.
--   3. Changes the functions that send machines to the apps, so that the seat
--      travels next to the name and the code:
--        * report_json   -> inside every report: machine.seat
--        * list_machines -> seat
--      Every other function that returns a report already uses report_json, so
--      they get the new field for free.
--
-- Why: without a seat, the website sorts the machines by name and counts them
-- into rows of six, so adding or renaming one machine can move the others to a
-- different place. A fixed seat keeps every machine where it is. Mithi asked for
-- it in requests/sakib/2026-11-07-machine-seat-place.md.
--
-- How the apps use it (docs/api-contract.md section 3):
--   * The seat is OPTIONAL. When a machine has none, the field is `null`, and the
--     map falls back to sorting by name.
--   * Nothing is generated by the apps. A person (Sakib) types each seat.
--
-- Nothing else changes: the same function names, inputs, permissions and error
-- codes. Only an extra field appears in the results, so the apps keep working
-- before and after this file. "create or replace" keeps the existing permissions
-- of each function.
--
-- Rules for this folder (see supabase/CLAUDE.md):
--   * Never edit an old migration. Add a NEW file for every change.
-- =============================================================================


-- -----------------------------------------------------------------------------
-- 1. The new, optional, unique column
-- -----------------------------------------------------------------------------
-- A seat is either empty or one capital letter (the row) followed by a place
-- number of 1 or 2 digits that does not start with 0, for example A1, B6, C12.
-- `unique` allows many empty seats but never two equal ones.
-- The table stays locked: this column inherits the lock.
alter table public.machines
  add column seat text unique
  check (seat is null or seat ~ '^[A-Z][1-9][0-9]?$');


-- -----------------------------------------------------------------------------
-- 2. The seats of the machines that exist today
-- -----------------------------------------------------------------------------
-- Sorted by name, in rows of six, exactly like the map shows them now.
update public.machines m
set seat = v.seat
from (values
  ('Cutting machine 03',  'A1'),
  ('Pressing machine 01', 'A2'),
  ('Sewing machine 01',   'A3'),
  ('Sewing machine 02',   'A4'),
  ('Sewing machine 14',   'A5')
) as v (name, seat)
where m.name = v.name
  and m.seat is null;


-- -----------------------------------------------------------------------------
-- 3. One report, in the shape of docs/api-contract.md section 3
-- -----------------------------------------------------------------------------
-- Same as migration 12, plus machine.seat. `technician` is still JSON null when
-- nobody is assigned yet.
create or replace function public.report_json(p_report public.reports)
returns jsonb
language sql
stable
security definer
set search_path = ''
as $$
  select jsonb_build_object(
    'id', p_report.id,
    'machine', (
      select jsonb_build_object(
        'id', m.id, 'name', m.name, 'name_bn', m.name_bn, 'code', m.code, 'seat', m.seat
      )
      from public.machines m
      where m.id = p_report.machine_id
    ),
    'description', p_report.description,
    'status', p_report.status,
    'reported_by', (
      select jsonb_build_object(
        'id', w.id, 'display_name', w.display_name, 'display_name_bn', w.display_name_bn
      )
      from public.profiles w
      where w.id = p_report.reported_by
    ),
    'technician', (
      select jsonb_build_object(
        'id', t.id, 'display_name', t.display_name, 'display_name_bn', t.display_name_bn
      )
      from public.profiles t
      where t.id = p_report.technician_id
    ),
    'accepted_at', p_report.accepted_at,
    'created_at', p_report.created_at,
    'updated_at', p_report.updated_at
  );
$$;


-- -----------------------------------------------------------------------------
-- 4. The machine list (worker's dropdown, manager)
-- -----------------------------------------------------------------------------
create or replace function public.list_machines()
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
begin
  perform public.require_role(array['worker', 'manager']::public.user_role[]);

  return (
    select coalesce(
      jsonb_agg(
        jsonb_build_object(
          'id', m.id, 'name', m.name, 'name_bn', m.name_bn, 'code', m.code, 'seat', m.seat
        )
        order by m.name
      ),
      '[]'::jsonb
    )
    from public.machines m
  );
end;
$$;
